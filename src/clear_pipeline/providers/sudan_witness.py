"""Sudan Witness (Centre for Information Resilience) client — verified
open-source evidence (videos, photos, satellite imagery) on CIR's public
ArcGIS feature layer. No authentication.

One row = one piece of evidence, not one event: a single video is often split
into several timestamped rows, each its own signal. Every row is "Reviewed -
Verified" (location verified; the date often is only the post date — see
`D_Chronolocation_status`, carried into the description).

Fetch semantics (why this looks like IDMC, not ACLED):
  - CIR republishes the whole layer from its internal database (cadence
    unknown), and rows land weeks to months after their event date. A date
    watermark would skip them, so a poll fetches every row dated on/after
    `sudan_witness_min_incident_date` (in the query, then again client-side)
    and gx's content hash skips unchanged rows.
  - The full pull is gated on the layer fingerprint (`dataLastEditDate` +
    row count, whole layer, + the floor so lowering it re-pulls): unchanged
    since the last clean poll → nothing
    fetched, so bronze doesn't rewrite blobs for nothing. The fingerprint is committed
    by `set_last_synced`, which gx calls only after a clean bronze batch. A full
    pull is forced anyway once `since` is older than
    `sudan_witness_full_pull_max_age_hours` — the safety net for a failure
    after bronze, and for a republish that leaves `dataLastEditDate` unchanged
    (unverified either way).
  - `OBJECTID1` is regenerated on republish; the key is `Entry_Number`,
    normalised to its integer (CIR's zero-padding varies: SUW0050 vs SUW3217).
  - Any HTTP / ArcGIS / malformed-response failure raises (a broken endpoint
    never looks like an unchanged layer), and so does a pull republished
    mid-way or whose size differs from the floored count (no mixed-version or
    short batch reaches CLEAR). gx bronze fails; the next poll pulls again.

Known gaps:
  - A row CIR withdraws (or re-dates below the floor) disappears from the pull;
    gx has no "absent from a full snapshot" retraction yet, so it stays live.
  - No casualties: the layer has no count field (`E_Affected_Persons` is
    categorical) and the free text carries only unverified poster claims.

Endpoint: settings.sudan_witness_layer_url.
"""

import hashlib
import json
import logging
import re
from datetime import UTC, datetime
from typing import Any, cast

import httpx
import redis

# Generic over CreateSignalInput keys — the same adapter IDMC uses for revisions.
from clear_pipeline.providers.alert_severity import llm_severity_or_none
from clear_pipeline.providers.idmc import build_signal_content_update
from clear_pipeline.signals.config import settings

logger = logging.getLogger(__name__)

_redis = redis.from_url(settings.redis_url, decode_responses=True)

__all__ = [
    "build_signal_content_update",
    "build_sudan_witness_signal_input",
    "fetch_sudan_witness_records",
    "get_last_synced",
    "parse_feature",
    "set_last_synced",
]

_ENTRY_NUMBER = re.compile(r"SUW(\d+)")
# Regenerated by ArcGIS on every republish — must not count as a revision.
_UNSTABLE_FIELDS = ("OBJECTID1",)
_SYNCED_KEY = "suw:last_synced"
_FINGERPRINT_KEY = "suw:layer_fingerprint"

# Fingerprint of the last pull, committed by `set_last_synced` once gx's bronze
# batch lands cleanly. Process-local: bronze polls and sets the watermark in
# the same op.
_pending_fingerprint: str | None = None

# Video-segment prefixes CIR puts in front of the description:
# "[0:12 - 0:20] …", "(0:55 - 1:11) …", "Video (@1:03) …", "[Original] …".
_TITLE_PREFIX = re.compile(
    r"^\s*(\[[^\]]*\d:\d{2}[^\]]*\]|\([^)]*\d:\d{2}[^)]*\)|\[Original\]|(Video|Clip)\s*\(@?\d{1,2}:\d{2}\))\s*[-–:]?\s*",
    re.I,
)
# Links an analyst can't open: Firebase Dynamic Links (shut down Aug 2025),
# CIR's Drive (sign-in wall), signed Facebook CDN URLs (expire). Kept in rawData.
_UNUSABLE_LINK_MARKERS = ("page.link/", "drive.google.com/", "fbcdn.net/")

# (label, attribute) pairs appended to the description — the classifier's context.
_DESCRIPTION_FIELDS = (
    ("Category", "Map_category"),
    ("Forms of violence", "E_Forms_of_violence"),
    ("Harm to persons", "E_Harm_to_Persons"),
    ("Affected persons", "E_Affected_Persons"),
    ("Target type", "E_Location_Or_Nature"),
    ("Armed-group activity", "E_Activities_of_military_police_and_armed_groups"),
    # Kept apart on purpose: visible is verified in the footage, alleged is a claim.
    ("Visible perpetrator (verified)", "E_Visible_Verified_Perpetrators"),
    ("Alleged perpetrator (claimed)", "E_Alleged_claimed_Perpetrators"),
    ("Arms and munitions", "E_Arms_and_or_munitions"),
    ("Evidence type", "B_Data_Type"),
    ("Location basis", "D_Location_status"),
)


# ──────────────────────────────────────────────────────────────────────────────
# Fetch
# ──────────────────────────────────────────────────────────────────────────────
def _get(url: str, **params: str) -> dict:
    resp = httpx.get(url, params={**params, "f": "json"}, timeout=60)
    resp.raise_for_status()
    body = resp.json()
    if "error" in body:  # ArcGIS reports errors with HTTP 200
        raise RuntimeError(f"ArcGIS error: {body['error']}")
    return body


def _data_last_edit() -> int:
    return _get(settings.sudan_witness_layer_url)["editingInfo"]["dataLastEditDate"]


def _count(where: str = "1=1") -> int:
    return _get(f"{settings.sudan_witness_layer_url}/query", where=where, returnCountOnly="true")["count"]


def _fingerprint_of(edit: int, total: int) -> str:
    """`edit:total:floor`. The floor is ours, not the layer's: without it, lowering
    it would not re-pull an unchanged layer. The edit date is always first."""
    return f"{edit}:{total}:{settings.sudan_witness_min_incident_date.isoformat()}"


def _fingerprint() -> str:
    """Cheap layer version: 2 requests, no features. Whole layer, not floored."""
    return _fingerprint_of(_data_last_edit(), _count())


def _edit_date(ms: int | str) -> str:
    return datetime.fromtimestamp(int(ms) / 1000, UTC).isoformat()


def _floor_ms() -> int:
    floor = settings.sudan_witness_min_incident_date
    return int(datetime(floor.year, floor.month, floor.day, tzinfo=UTC).timestamp() * 1000)


def _floor_where() -> str:
    return f"D_Verified_Date >= DATE '{settings.sudan_witness_min_incident_date.isoformat()}'"


def _pull_features(where: str) -> list[dict]:
    query_url = f"{settings.sudan_witness_layer_url}/query"
    features: list[dict] = []
    while True:
        page = _get(
            query_url,
            where=where,
            outFields="*",
            returnGeometry="true",
            outSR="4326",
            orderByFields="OBJECTID1",
            resultOffset=str(len(features)),
            resultRecordCount=str(settings.sudan_witness_page_size),
        )
        batch = page["features"]
        features += batch
        if not page.get("exceededTransferLimit"):
            return features
        if not batch:  # same offset again → infinite loop
            raise RuntimeError(f"ArcGIS page at offset {len(features)} empty despite exceededTransferLimit")


def _fetch_all() -> tuple[list[dict], str]:
    """Every feature since the floor, from one consistent layer version, and that
    version's fingerprint. Raises if the layer was republished mid-pull or the
    pull came back short; nothing is committed, so the next poll pulls again."""
    where = _floor_where()
    before = _data_last_edit()
    logger.info("[SUDAN_WITNESS] layer last edited %s — pulling", _edit_date(before))
    total, count = _count(), _count(where)
    features = _pull_features(where)
    if _data_last_edit() != before:
        raise RuntimeError("Sudan Witness layer republished during the pull")
    if len(features) != count:
        raise RuntimeError(f"Sudan Witness pull returned {len(features)} features, floored count says {count}")
    logger.info("[SUDAN_WITNESS] fetched %d features", len(features))
    return features, _fingerprint_of(before, total)


def _unchanged_fingerprint(since: datetime | None) -> str | None:
    """Stored fingerprint if the last clean poll is recent and the layer still
    matches it (a pull would only re-fetch rows gx holds), else None."""
    if since is None:
        return None
    if (datetime.now(UTC) - since).total_seconds() >= settings.sudan_witness_full_pull_max_age_hours * 3600:
        return None
    stored = cast("str | None", _redis.get(_FINGERPRINT_KEY))
    if stored is None:
        return None
    try:
        current = _fingerprint()
    except (httpx.HTTPError, RuntimeError, KeyError, ValueError) as e:
        logger.warning("[SUDAN_WITNESS] fingerprint check failed (%s) — full pull", type(e).__name__)
        return None
    return stored if current == stored else None


def _content_hash(attributes: dict) -> str:
    """Fingerprint of a row's attributes, minus fields ArcGIS regenerates on
    republish. Geometry is left out: it always equals D_Latitude/D_Longitude."""
    stable = {k: v for k, v in attributes.items() if k not in _UNSTABLE_FIELDS}
    serialized = json.dumps(stable, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(serialized.encode("utf-8")).hexdigest()[:16]


def parse_feature(feature: dict) -> dict | None:
    """Normalise one ArcGIS feature into a record, or None when it can't become
    a signal: no usable `Entry_Number`, or no `D_Verified_Date` (gx's bronze
    gate requires a publication date)."""
    attributes = feature.get("attributes") or {}
    match = _ENTRY_NUMBER.fullmatch((attributes.get("Entry_Number") or "").strip())
    if not match:
        logger.warning("[SUDAN_WITNESS] unusable Entry_Number: %r", attributes.get("Entry_Number"))
        return None
    if attributes.get("D_Verified_Date") is None:
        logger.warning("[SUDAN_WITNESS] %s has no D_Verified_Date — skipped", attributes["Entry_Number"])
        return None
    published_at = datetime.fromtimestamp(attributes["D_Verified_Date"] / 1000, UTC).isoformat()
    return {
        "suw_id": f"suw:{int(match.group(1))}",
        "published_at": published_at,
        "content_hash": _content_hash(attributes),
        "raw": feature,
    }


def fetch_sudan_witness_records(since: datetime | None = None) -> list[dict]:
    """Every row dated on/after the floor as a parsed record, filtered to
    `sudan_witness_countries` (rows with no country are kept: in practice they
    sit inside Sudan, and clear-api resolves the location from the coordinates).
    `since` (the last clean poll) only gates the pull: [] when the layer hasn't
    changed since — see the module docstring. Raises on fetch failure."""
    global _pending_fingerprint
    _pending_fingerprint = None  # a raise below must not leave a stale one to commit
    if stored := _unchanged_fingerprint(since):
        logger.info(
            "[SUDAN_WITNESS] layer unchanged since %s (last edited %s) — nothing fetched",
            since, _edit_date(stored.split(":")[0]),
        )
        return []
    features, _pending_fingerprint = _fetch_all()
    countries = {c.strip() for c in settings.sudan_witness_countries.split(",") if c.strip()}
    floor_ms = _floor_ms()
    records: list[dict] = []
    skipped = before_floor = filtered_out = duplicates = 0
    seen: set[str] = set()
    for feature in features:
        record = parse_feature(feature)
        if record is None:
            skipped += 1
            continue
        # Server already floors; guards against a misread date clause.
        if record["raw"]["attributes"]["D_Verified_Date"] < floor_ms:
            before_floor += 1
            continue
        country = record["raw"]["attributes"].get("D_Country")
        if country is not None and country not in countries:
            filtered_out += 1
            continue
        if record["suw_id"] in seen:
            duplicates += 1
            continue
        seen.add(record["suw_id"])
        records.append(record)
    logger.info(
        "[SUDAN_WITNESS] %d records (skipped=%d, before_floor=%d, outside_countries=%d, duplicate_id=%d)",
        len(records), skipped, before_floor, filtered_out, duplicates,
    )
    return records


def get_last_synced() -> datetime | None:
    """Time of the last clean poll — gates the next pull, never filters rows."""
    val = cast("str | None", _redis.get(_SYNCED_KEY))
    return datetime.fromisoformat(val) if val else None


def set_last_synced(ts: datetime) -> None:
    """Called by gx after a clean bronze batch: commits the pulled fingerprint
    with it, so a failed batch is pulled again next poll."""
    _redis.set(_SYNCED_KEY, ts.isoformat())
    if _pending_fingerprint is not None:
        _redis.set(_FINGERPRINT_KEY, _pending_fingerprint)


# ──────────────────────────────────────────────────────────────────────────────
# Signal mapping
# ──────────────────────────────────────────────────────────────────────────────
def _tokens(value: Any) -> list[str]:
    return [t.strip() for t in str(value or "").split(",") if t.strip()]


def _clean_title(text: str) -> str:
    return _TITLE_PREFIX.sub("", text).strip() or text.strip()


def _clean_url(link: Any) -> str | None:
    """A link an analyst can open, or None. Malformed links get their scheme back."""
    url = str(link or "").strip()
    if not url or any(marker in url for marker in _UNUSABLE_LINK_MARKERS):
        return None
    return url if re.match(r"https?://", url) else f"https://{url}"


def _place(attributes: dict) -> str | None:
    # D_States is "English (Arabic transliteration)", sometimes with U+200E marks.
    state = str(attributes.get("D_States") or "").replace("\u200e", "").split(" (")[0].strip()
    parts = [p for p in (attributes.get("D_City"), state, attributes.get("D_Country")) if p]
    return ", ".join(parts) or None


def _description(attributes: dict) -> str:
    """The full brief (video timestamps kept — they tell segments apart), then
    CIR's classification as labelled lines for the classifier."""
    lines = [str(attributes.get("C_Brief_Description") or "").strip()]
    place = _place(attributes)
    if place:
        lines.append(f"Place: {place}")
    for label, field in _DESCRIPTION_FIELDS:
        values = _tokens(attributes.get(field))
        if values:
            lines.append(f"{label}: {', '.join(values)}")
    date_basis = ", ".join(_tokens(attributes.get("D_Chronolocation_status"))) or "not stated"
    lines.append(f"Date basis: {date_basis}")
    return "\n".join(line for line in lines if line)


def build_sudan_witness_signal_input(record: dict, source_id: str) -> dict:
    """Convert a parsed record into a CLEAR CreateSignalInput dict. A pure
    transform: no geoparser (CIR's coordinates are point-level, better than
    anything parsed from text) and no clear-api write.

    rawData is the attribute dict only — the geometry duplicates its
    coordinates. No `casualties` and no `media` (see the module docstring)."""
    attributes = record["raw"]["attributes"]
    brief = str(attributes.get("C_Brief_Description") or "")
    title = _clean_title(brief)
    description = _description(attributes)
    country = attributes.get("D_Country") or _place(attributes)
    severity = llm_severity_or_none(
        country=country if isinstance(country, str) else None,
        event_name=title,
        event_description=description,
        log_tag=f"sudan_witness:{record.get('suw_id')}",
    )
    input_data: dict = {
        "sourceId": source_id,
        "externalId": record["suw_id"],
        "rawData": attributes,
        "publishedAt": record["published_at"],
        "title": title,
        "description": description,
        "severity": severity,
        "url": _clean_url(attributes.get("Link")),
        "contentHash": record["content_hash"],
    }
    lat, lng = attributes.get("D_Latitude"), attributes.get("D_Longitude")
    if isinstance(lat, (int, float)) and isinstance(lng, (int, float)):
        # Server-side PostGIS geo-resolution into a general locationId.
        input_data["lat"] = lat
        input_data["lng"] = lng
    return input_data
